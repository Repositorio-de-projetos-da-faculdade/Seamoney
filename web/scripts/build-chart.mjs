// Builds the coastline of the SaaS demo's nautical chart: Natural Earth land (1:50m, public domain, via world-atlas)
// projected in Mercator, the projection of navigation charts, over the waters between Santos and northern China.
// Output: src/lib/chart/land.ts (an SVG path plus the projection constants). Run after changing the region:
//   node scripts/build-chart.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { geoMercator, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'
import { presimplify, quantile, simplify } from 'topojson-simplify'

const REGION = { west: -58, east: 128, north: 36, south: -44 }
const WIDTH = 1600

const rad = (d) => (d * Math.PI) / 180
const mercY = (lat) => Math.log(Math.tan(Math.PI / 4 + rad(lat) / 2))

const k = WIDTH / rad(REGION.east - REGION.west)
const tx = -k * rad(REGION.west)
const ty = k * mercY(REGION.north)
const HEIGHT = Math.round(k * (mercY(REGION.north) - mercY(REGION.south)))

const projection = geoMercator()
  .scale(k)
  .translate([tx, ty])
  .clipExtent([
    [-20, -20],
    [WIDTH + 20, HEIGHT + 20],
  ])

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url), 'utf8'))
const pre = presimplify(topo)
// drop the smallest 35% of detail: invisible at this scale, and it halves the file
const land = feature(simplify(pre, quantile(pre, 0.35)), topo.objects.land)
const d = geoPath(projection).digits(1)(land)

const out = `// Generated by scripts/build-chart.mjs from Natural Earth 1:50m land (public domain). Do not edit by hand.
export const CHART = { width: ${WIDTH}, height: ${HEIGHT}, k: ${k.toFixed(4)}, tx: ${tx.toFixed(4)}, ty: ${ty.toFixed(4)} } as const
export const REGION = ${JSON.stringify(REGION)} as const
export const LAND_PATH =
  '${d}'
`
writeFileSync(new URL('../src/lib/chart/land.ts', import.meta.url), out)
console.log(`land.ts: ${(out.length / 1024).toFixed(1)} KB, viewBox 0 0 ${WIDTH} ${HEIGHT}`)
